#pragma once

#include <cstdint>
#include <string>
#include <vector>

// ТЗ Рівень 3: реєстр налаштувань КНЕДП із `CAs.json` ЦЗО.
//
// Навіщо окремо від довірчого списку. `TL-UA-EC.xml`, який Tamga вже розбирає,
// містить лише HTTP(S)-точки OCSP/CRL/TSP і жодного `cmpAddress` — перевірено
// на реальному артефакті. Адреси CMP публікуються тільки в `CAs.json`, і без
// них Рівень 3 не має куди звертатись за сертифікатом підписувача.
//
// Формат виміряно на справжньому файлі ЦЗО (33 записи):
//   issuerCNs[], address, ocspAccessPointAddress/Port, cmpAddress,
//   tspAddress/Port, codeEDRPOU, directAccess?, cmpCompatibility?,
//   qscdSNInCert?, certsInKey?
// Поля-адреси подекуди вже містять шлях (`ca.gp.gov.ua/cmp`), подекуди ні
// (`ca.tax.gov.ua`) — нормалізація враховує обидва випадки.

namespace tamga::core::net {

struct CaSettingsEntry {
    std::vector<std::string> issuer_cns;
    std::string address;
    std::string edrpou;
    // Готові до вживання URL (схема+host+порт+шлях), а не сирі поля JSON.
    std::string ocsp_url;
    std::string cmp_url;
    std::string tsp_url;
    bool direct_access{false};
};

class CaSettingsRegistry final {
public:
    // Розбирає вміст `CAs.json`.
    //
    // Документ приймається лише ЦІЛИМ: масив має бути закритий, кожен його
    // елемент — синтаксично завершений, а після масиву не має лишатися нічого,
    // крім пробільних символів. Q-05: до виправлення обірваний
    // `[{"address":"ca.example"` повертав `true` з одним придатним записом і
    // міг потрапити в кеш як повний реєстр.
    //
    // Окремий запис пропускається, коли він структурно завершений, але
    // непридатний (немає `address`, значення не того типу) — реєстр із 32
    // придатних КНЕДП корисніший за повну відмову через один такий запис.
    // Запис, межі якого встановити НЕМОЖЛИВО, відхиляє весь документ: це вже
    // не «один битий запис», а невідомо скільки.
    static bool ParseJson(const std::string& json,
                          std::vector<CaSettingsEntry>& out,
                          std::string& error_message);

    // Читає `<work_dir>/CAs.json`; за наявності мережі (offline=false) і
    // відсутності/застарілості кешу — довантажує з `url` і зберігає.
    //
    // Політика (реалізована; до 2026-09-09 кеш був вічний — будь-який
    // розбірний `CAs.json` повертався одразу, до перевірки `offline`, без TTL
    // і без звірки з джерелом, тож переїзд адрес КНЕДП не впливав на вже
    // наповнений кеш, а онлайн-режим ніколи не оновлював реєстр):
    //   1. Кеш вважається придатним лише коли він (а) розібрався, (б) записаний
    //      із того самого джерела, що й ефективний `url` (порожній `url` —
    //      `DefaultUrl()`), і (в) не старший за TTL. TTL — доба; джерело
    //      зберігається поруч із кешем, бо самого файлу для звірки не досить.
    //   2. `offline=true`: придатність за TTL і джерелом не перевіряється —
    //      альтернативи однаково немає, тож використовується будь-який
    //      розбірний кеш. Немає кешу — відмова, як і зараз.
    //   3. `offline=false`: придатний кеш повертається без мережі; непридатний
    //      (застарілий, від іншого джерела, відсутній) — довантаження з `url`,
    //      і лише успішно розібране тіло перезаписує кеш.
    //   4. Якщо довантаження не вдалося, а непридатний кеш є, він
    //      використовується як запасний варіант: застарілий реєстр КНЕДП
    //      кращий за повну відмову резолвера. Це не послаблює безпеку —
    //      реєстр дає лише адреси, а придатність самого сертифіката
    //      вирішує fail-closed звірка з відкритим ключем у
    //      `CertificateResolver`.
    static bool Load(const std::string& work_dir,
                     bool offline,
                     const std::string& url,
                     std::int32_t timeout_ms,
                     std::vector<CaSettingsEntry>& out,
                     std::string& error_message);

    // Пошук за ЄДРПОУ (точно), адресою (точно) або підрядком CN видавця
    // (без урахування регістру для ASCII). nullptr, якщо не знайдено.
    static const CaSettingsEntry* Find(const std::vector<CaSettingsEntry>& entries,
                                       const std::string& hint);

    static const char* DefaultUrl();
};

}  // namespace tamga::core::net
