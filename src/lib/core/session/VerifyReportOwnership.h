#pragma once

#include <cstdint>

namespace tamga::core {

// Н-04 (TOCTOU звіту), винесено з `Session` як самостійний шов (ADR-033).
//
// Verify-операції навмисно НЕ тримають мутекс сесії під час роботи (WP-17:
// мережеві OCSP/CRL/TSA-виклики поза критичною секцією). Через це між комітом
// звіту і подальшим доуточненням окремих полів мутекс відпускається — і
// паралельний Verify* на ТІЙ САМІЙ сесії встигає закомітити СВІЙ звіт.
// Доуточнення тоді потрапляло в чужий звіт: операція чи статус мітки часу від
// одного виклику опинялися в результаті іншого.
//
// Тримати мутекс на всю операцію не можна — це відкотило б WP-17 і повернуло
// блокування GetReport() на час мережевих викликів. Тому замість розширення
// критичної секції введено ЕПОХУ звіту: кожен коміт отримує глобально
// унікальний номер, а доуточнення застосовується лише тоді, коли поточний звіт
// — усе ще той, який закомітив ЦЕЙ потік.
//
// Лічильник глобальний, а не по-сесійний, навмисно: інакше два різні Session
// могли б видати однакове число, і доуточнення від одного помилково збіглося б
// з епохою іншого. Атомарний, бо сесії живуть у різних потоках.
//
// Клас НЕ має власної синхронізації: викликач (Session) уже тримає свій
// мутекс. Виділення в окремий тип потрібне не задля блокування, а щоб
// інваріант «доуточнюю лише власний звіт» можна було перевірити прямо —
// двома потоками над двома обʼєктами, без ключів, файлів і мережі.
class VerifyReportOwnership {
public:
    // Фіксує новий коміт: звіт тепер належить потоку, що викликав.
    void MarkCommitted();

    // Чи звіт усе ще той, який закомітив ЦЕЙ потік.
    [[nodiscard]] bool StillOwnedByThisThread() const;

    // Лише для діагностики й тестів: 0 означає «жодного коміту не було».
    [[nodiscard]] std::uint64_t epoch() const { return epoch_; }

private:
    std::uint64_t epoch_{0};
};

} // namespace tamga::core
